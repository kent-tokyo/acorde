#![cfg(all(feature = "musicxml", feature = "mscz"))]
use acorde_core::{Score, to_playback_events};

fn symbols(score: &Score) -> Vec<(String, String, Option<String>)> {
    score.parts[0].staves[0].measures[0].voices[0]
        .iter()
        .filter_map(|note| {
            note.chord_symbol
                .as_ref()
                .map(|chord| (chord.root.clone(), chord.kind.clone(), chord.bass.clone()))
        })
        .collect()
}
fn events(score: &Score) -> Vec<(u8, i64, i64)> {
    to_playback_events(score, &Default::default())
        .into_iter()
        .map(|event| {
            (
                event.pitch_midi,
                (event.time_beats * 960.0).round() as i64,
                (event.duration_beats * 960.0).round() as i64,
            )
        })
        .collect()
}

#[test]
fn preserves_musescore_475_harmony_roots_and_slash_basses() {
    // Generated by MuseScore Studio 4.7.5 from issue_476_harmony.musicxml.
    let native = acorde_io::parse_mscz(include_bytes!(
        "../../../tests/fixtures/issue_476_musescore475.mscz"
    ))
    .unwrap();
    let input = acorde_io::parse_musicxml(include_str!(
        "../../../tests/fixtures/issue_476_harmony.musicxml"
    ))
    .unwrap();
    let expected = vec![
        ("C".into(), "major".into(), None),
        ("G".into(), "dominant".into(), None),
        ("Bb".into(), "minor".into(), Some("D".into())),
        ("F#".into(), "dominant".into(), Some("C#".into())),
    ];
    assert_eq!(symbols(&native), expected);
    assert_eq!(symbols(&input), expected);
    let xml = acorde_io::serialize_mscx(&input).unwrap();
    assert!(xml.contains("<museScore version=\"4.60\">"));
    assert!(xml.contains("<harmonyInfo><name>7</name><root>15</root></harmonyInfo>"));
    assert!(
        xml.contains("<harmonyInfo><name>m</name><root>12</root><bass>16</bass></harmonyInfo>")
    );
    let restored = acorde_io::parse_mscz(&acorde_io::serialize_mscz(&input).unwrap()).unwrap();
    assert_eq!(symbols(&restored), expected);
    assert_eq!(events(&input), events(&restored));
}
